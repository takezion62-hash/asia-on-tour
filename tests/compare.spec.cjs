'use strict';
const {test,expect}=require('@playwright/test');
const path=require('node:path');
const {loadData}=require('../scripts/data-checks.cjs');
const data=loadData(path.join(__dirname,'..')).data;
const nameA='Shiroka',nameB='かめてぃん',nameC='3peace';
const compareURL=(players=[nameA,nameB],params={})=>{
 const url=new URLSearchParams();
 for(const name of players)url.append('player',name);
 for(const [k,v] of Object.entries(params))url.set(k,v);
 return '/?season=all#compare?'+url.toString();
};

test('比較エンジン・CSSがテストサーバーから配信され、ナビから比較ページを開ける',async({page,request})=>{
 const js=await request.get('/compare.js'),css=await request.get('/compare.css');
 expect(js.status()).toBe(200);expect(css.status()).toBe(200);
 expect(await js.text()).toContain('AsiaCompare');
 expect(await css.text()).toContain('.compare-table');
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/?season=all#home');
 await page.locator('.nav button[data-page="compare"]').click();
 await expect(page.locator('#page-compare')).toBeVisible();
 await expect(page.locator('#compare-title')).toHaveText('選手比較');
 await expect(page.locator('#compare-report')).toHaveAttribute('data-compare-selected','2');
 expect(errors).toEqual([]);
});
test('2人を比較して3人目を追加・除外でき、比較リンクに全員の名前を保存する',async({page})=>{
 await page.goto(compareURL());
 await expect(page.locator('#page-compare')).toBeVisible();
 await expect(page.locator('[data-compare-summary]')).toHaveCount(2);
 await expect(page.locator('[data-compare-metric]')).toHaveCount(8);
 await expect(page.locator('[data-compare-value="pr"]')).toHaveCount(2);
 await expect(page.locator('[data-compare-value="cash"]')).toHaveCount(2);
 await expect(page.locator('[data-compare-value="vrs"]')).toHaveCount(2);
 await expect(page.locator('.compare-region-table tbody tr')).toHaveCount(6);
 await page.locator('#compare-player-input').fill(nameC);
 await page.locator('#compare-add-form button[type="submit"]').click();
 await expect(page.locator('[data-compare-summary]')).toHaveCount(3);
 await expect(page.locator('[data-compare-player="'+nameC+'"]')).toHaveCount(1);
 await expect(page.locator('[data-compare-value="pr"]')).toHaveCount(3);
 const currentURL=page.url();
 expect(currentURL).toContain(encodeURIComponent(nameA));
 expect(currentURL).toContain(encodeURIComponent(nameB));
 expect(currentURL).toContain('3peace');
 await page.reload();
 await expect(page.locator('[data-compare-summary]')).toHaveCount(3);
 await page.locator('[data-compare-remove="'+nameC+'"]').click();
 await expect(page.locator('[data-compare-summary]')).toHaveCount(2);
 await expect(page.locator('#compare-share')).toHaveAttribute('href',/player=Shiroka/);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth+2)).toBe(true);
});
test('入力ミス・重複を弾き、3人が上限で名前の誤名寄せをしない',async({page})=>{
 await page.goto(compareURL());
 await page.locator('#compare-player-input').fill('shiroka');
 await page.locator('#compare-add-form button[type="submit"]').click();
 await expect(page.locator('#compare-add-error')).toContainText('候補一覧');
 await expect(page.locator('[data-compare-summary]')).toHaveCount(2);
 await page.locator('#compare-player-input').fill(nameA);
 await page.locator('#compare-add-form button[type="submit"]').click();
 await expect(page.locator('#compare-add-error')).toContainText('すでに');
 await page.locator('#compare-player-input').fill(nameC);
 await page.locator('#compare-add-form button[type="submit"]').click();
 await expect(page.locator('[data-compare-summary]')).toHaveCount(3);
 await expect(page.locator('#compare-player-input')).toBeDisabled();
 await expect(page.locator('#compare-add-form button[type="submit"]')).toBeDisabled();
});
test('シーズン・地域・形式・シリーズの比較条件を揃えて、数値とURLを更新する',async({page})=>{
 await page.goto(compareURL());
 const a=page.locator('[data-compare-summary="'+nameA+'"]');
 const countBefore=await page.locator('[data-compare-value="results"][data-compare-player="'+nameA+'"] strong').innerText();
 await page.locator('#compare-filter-region').selectOption('ME');
 await expect(page.locator('#compare-filter-region')).toHaveValue('ME');
 await expect(page).toHaveURL(/region=ME/);
 const countME=await page.locator('[data-compare-value="results"][data-compare-player="'+nameA+'"] strong').innerText();
 expect(Number(countME.replace(/,/g,''))).toBeLessThanOrEqual(Number(countBefore.replace(/,/g,'')));
 await page.locator('#compare-filter-mode').selectOption('reload');
 await expect(page).toHaveURL(/mode=reload/);
 await page.locator('#compare-filter-series').selectOption('cash-cup');
 await expect(page).toHaveURL(/series=cash-cup/);
 await expect(page.locator('.compare-footnote')).toContainText('確認済み');
 await page.locator('#compare-filter-season').selectOption('S42');
 await expect(page.locator('#season-select')).toHaveValue('S42');
 await expect(page).toHaveURL(/season=S42/);
 await expect(page.locator('[data-compare-summary]')).toHaveCount(2);
 await page.reload();
 await expect(page.locator('#compare-filter-mode')).toHaveValue('reload');
 await expect(page.locator('#compare-filter-region')).toHaveValue('ME');
 await expect(page.locator('#compare-filter-series')).toHaveValue('cash-cup');
 await expect(page.locator('#compare-filter-season')).toHaveValue('S42');
});
test('プロフィールから比較ページへ追加し、1人の時は追加案内が表示される',async({page})=>{
 await page.goto('/?season=all#player='+encodeURIComponent(nameA));
 await expect(page.locator('#page-profile')).toBeVisible();
 await page.locator('[data-compare-profile="'+nameA+'"]').click();
 await expect(page.locator('#page-compare')).toBeVisible();
 await expect(page.locator('[data-compare-selected="1"]')).toBeVisible();
 await expect(page.locator('.compare-empty')).toContainText('あと1人');
 await page.locator('#compare-player-input').fill(nameB);
 await page.locator('#compare-add-form button[type="submit"]').click();
 await expect(page.locator('[data-compare-summary]')).toHaveCount(2);
 await page.goBack();
 await expect(page.locator('#page-compare')).toBeVisible();
 await expect(page.locator('[data-compare-selected="1"]')).toBeVisible();
 await page.goBack();
 await expect(page.locator('#page-profile')).toBeVisible();
});
test('不正な比較URLを安全に正規化し、空選択も維持する',async({page})=>{
 await page.goto(compareURL(['Unknown',nameA,nameB,nameC,'Extra']));
 await expect(page.locator('[data-compare-summary]')).toHaveCount(3);
 await expect(page.locator('[data-compare-summary="Unknown"]')).toHaveCount(0);
 await page.goto('/?season=all#compare?empty=1');
 await expect(page.locator('[data-compare-summary]')).toHaveCount(0);
 await expect(page.locator('.compare-empty')).toContainText('あと2人');
 await page.reload();
 await expect(page.locator('[data-compare-selected="0"]')).toBeVisible();
});
